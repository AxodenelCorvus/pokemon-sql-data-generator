package com.github.axodenelcorvus.writer;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;

public class PokemonSqlSeedFilesRemover extends SimpleFileVisitor<Path> {
    private int removalCount = 0;
    private final SqlSeedFilesContext filesContext;

    private final int removeGenerationStart;
    private final int removeGenerationInclusiveEnd;

    public PokemonSqlSeedFilesRemover(
            int removeGenerationStartFrom,
            int removeGenerationToInclusiveEnd,
            Path directoryDestination
    ) {
        this.filesContext = new SqlSeedFilesContext(directoryDestination);
        this.removeGenerationStart = removeGenerationStartFrom;
        this.removeGenerationInclusiveEnd = removeGenerationToInclusiveEnd;
    }

    public void removeAllTargetedSqlSeedFiles() throws IOException {
        Files.walkFileTree(filesContext.getDirectoryDestination(), this);
    }

    public int getRemovalCount() { return removalCount; }

    public int getGenerationTargetedRemovalRangeStart() {
        return removeGenerationStart;
    }

    public int getGenerationTargetedRemovalRangeEnd() {
        return removeGenerationInclusiveEnd;
    }

    public Path getTargetedDirectory() {
        return filesContext.getTargetDestination();
    }

    @Override
    public FileVisitResult preVisitDirectory(Path dir,
                                             BasicFileAttributes basicFileAttributes) {
        if (dir.equals(filesContext.getDirectoryDestination()))
            return FileVisitResult.CONTINUE;
        else  //Silently skip any nested directories,
            return FileVisitResult.SKIP_SUBTREE;
    }

    /*
    Skips or ignores files silently where:
        -File doesn't end with .sql (done first to skip fast and is most likely file to be skipped)
        -File name is less than length of the only possible prefix generated by application
        -File doesn't match a valid prefix format (the fixed prefix segment of the prefix first
        and then the next two chars of prefix padded to exactly 2 digits always)
        -File's prefix value is NOT in range this instance was configured with
    */
    @Override
    public FileVisitResult visitFile(Path fileCandidate,
                                     BasicFileAttributes fileAttrs) throws IOException {

        String fileCandidateName = fileCandidate.getFileName().toString();

        //Go ahead and silently skip any files without correct extension
        if (!fileCandidateName.endsWith(".sql"))
            return FileVisitResult.CONTINUE;

        //With '%' specifier excluded from len of the formater, it matches the length of prefix
        int prefixSubstrLength =
                SqlSeedFilesContext.SQL_FILE_PREFIX_FORMAT.length() - 1;

        //Silently skip any files where the name is far too short to be valid removal target
        if (fileCandidateName.length() < prefixSubstrLength)
            return FileVisitResult.CONTINUE;

        String fileCandidateNamePrefix = fileCandidateName.substring(0, prefixSubstrLength);

        int i = 0;
        i = moveIndexPastFixedPrefixSegment(i, fileCandidateNamePrefix);

        boolean isFileNotMatchedToFixedPrefixSegment = i < 0;

        if (isFileNotMatchedToFixedPrefixSegment)
            return FileVisitResult.CONTINUE;

        char secondToLastPrefixChar = fileCandidateNamePrefix.charAt(i);
        char lastPrefixChar = fileCandidateNamePrefix.charAt(i + 1);

        boolean areLastTwoCharsNotDigits =
                !Character.isDigit(secondToLastPrefixChar) || !Character.isDigit(lastPrefixChar);

        if (areLastTwoCharsNotDigits)
            return FileVisitResult.CONTINUE;

        int filePrefixValue = formFilePrefixValue(secondToLastPrefixChar, lastPrefixChar);

        if (filePrefixValue >= removeGenerationStart && filePrefixValue <= removeGenerationInclusiveEnd) {
            Files.delete(fileCandidate);
            removalCount++;
        }

        return FileVisitResult.CONTINUE;
    }

    private int formFilePrefixValue(char secondToLastPrefixChar, char lastPrefixChar) {
        return Character.getNumericValue(secondToLastPrefixChar) * 10
                + Character.getNumericValue(lastPrefixChar);
    }

    private int moveIndexPastFixedPrefixSegment(int idx, String fileCandidatePrefixToMatch) {
        String commonFixedPrefix = SqlSeedFilesContext.SHARED_FIXED_PREFIX_SEGMENT;

        for (idx = idx; idx < commonFixedPrefix.length(); idx++) {
            if (fileCandidatePrefixToMatch.charAt(idx) != commonFixedPrefix.charAt(idx))
                return -1;
        }

        return idx;
    }

}
